//! What the device's settings turn into on disk.
//!
//! Two files, both written only when their content actually changes - an
//! unchanged render must never restart anything, because a restart is a
//! blank screen in a public place:
//!
//! * `/run/tessaro-kiosk/generated.env`: the settings as `KIOSK_*=value`
//!   lines, for `tessaro-kiosk.service` (`EnvironmentFile=`, after the image
//!   defaults) and for `tessaro-weston-config`. Only the keys that were set:
//!   everything else already comes from the `/usr/lib` defaults.
//! * `/etc/chromium/policies/managed/10-tessaro.json`: the image's policy with
//!   the device-API grants rewritten for the kiosk origin *as set*, not as
//!   built. Generated through serde, because Chromium drops the whole file
//!   on one syntax error with a single `SYSLOG(WARNING)`.
//!
//! Values need no quoting in the env file: the registry has already refused
//! every character systemd's parser would treat specially.

use std::collections::BTreeMap;
use std::path::Path;

use serde_json::{Map, Value};

use crate::config::Env;
use crate::log::Log;
use crate::paths::Paths;
use crate::state;
use crate::store;

/// The two grants that follow the kiosk origin. Everything else in the policy
/// is the image's.
const ORIGIN_POLICIES: [&str; 2] = ["SerialAllowAllPortsForUrls", "WebHidAllowAllDevicesForUrls"];

pub fn env_file(
    settings: &BTreeMap<String, String>,
    defaults: &dyn Env,
    live: &state::Live,
    log: &Log,
) -> String {
    let mut out = String::from(
        "# Generated by tessaro-agent from /data/tessaro/state.json. Do not edit:\n\
         # change a setting with `tessaro-ctl set KEY=VALUE`, see `tessaro-ctl keys`.\n",
    );
    let overrides = state::overrides(settings, log);
    for key in protocol::keys::KEYS {
        if key.env == "KIOSK_URL" {
            continue; // below, expanded
        }
        if key.env == "KIOSK_MAINTENANCE_URL" {
            continue; // a template; in maintenance mode it *is* KIOSK_URL below
        }
        if key.kind == protocol::keys::Kind::Template {
            // The debug template's `\n` is the one backslash a value may hold,
            // and systemd would eat it unquoted. Only the agent reads it, and
            // it reads state.json.
            continue;
        }
        if let Some((env, value)) = overrides.iter().find(|(env, _)| *env == key.env) {
            out.push_str(&format!("{env}={value}\n"));
        }
    }

    // The kiosk URL goes out expanded, never as a template: the browser unit
    // opens ${KIOSK_URL} as it stands. Written whenever it differs from the
    // image default - set here, a default whose placeholders were filled, or
    // the maintenance page, so a reboot in maintenance never shows the site.
    let effective = state::Effective::new(defaults, settings, log).with_live(live.clone());
    if let Some(url) = effective.get("KIOSK_URL") {
        if defaults.get("KIOSK_URL").as_deref() != Some(url.as_str()) {
            out.push_str(&format!("KIOSK_URL={url}\n"));
        }
    }

    // Switches a flag turns into. systemd cannot make a flag conditional, so
    // the unit passes `$KIOSK_FPS_ARGS` (unbraced: empty means no argument
    // at all) and this is the one place that decides what it holds.
    if let Some((_, value)) = overrides
        .iter()
        .find(|(env, _)| *env == "KIOSK_FPS_COUNTER")
    {
        let args = if value == "1" {
            "--show-fps-counter"
        } else {
            ""
        };
        out.push_str(&format!("KIOSK_FPS_ARGS={args}\n"));
    }
    out
}

/// The device-API origins: the kiosk's, the self-test page's, and any extra
/// ones set, deduplicated and in that order. The kiosk's is kiosk.url's even
/// in maintenance mode, so toggling it never changes the policy.
pub fn device_origins(effective: &state::Effective, selftest_origin: &str) -> Vec<String> {
    let mut origins: Vec<String> = Vec::new();
    let kiosk_url = effective.kiosk_url().unwrap_or_default();
    let mut add = |origin: &str| {
        if !origin.is_empty() && !origins.iter().any(|known| known == origin) {
            origins.push(origin.to_string());
        }
    };

    if let Some(origin) = protocol::keys::origin_of(&kiosk_url) {
        add(origin);
    }
    add(selftest_origin);
    for origin in effective
        .get("KIOSK_DEVICE_ORIGINS")
        .unwrap_or_default()
        .split_whitespace()
    {
        add(origin);
    }
    origins
}

pub fn policy(base: &str, origins: &[String]) -> Result<String, String> {
    let mut document: Map<String, Value> = serde_json::from_str(&strict_json(base))
        .map_err(|err| format!("the base policy: {err}"))?;

    for name in ORIGIN_POLICIES {
        document.insert(
            name.to_string(),
            Value::Array(origins.iter().cloned().map(Value::String).collect()),
        );
    }

    let body = serde_json::to_string_pretty(&document).map_err(|err| err.to_string())?;
    Ok(format!(
        "// Generated by tessaro-agent from /usr/lib/tessaro-kiosk/policy.json,\n\
         // which carries the documentation for every entry. Do not edit: the\n\
         // device-API origins follow kiosk.url and browser.device_origins, set\n\
         // with tessaro-ctl. Check the result on chrome://policy.\n\
         {body}\n"
    ))
}

/// Chromium's policy loader accepts `//` and `/* */` comments and trailing
/// commas (`JSON_PARSE_CHROMIUM_EXTENSIONS`), and the shipped file uses all
/// three to document itself. serde_json accepts none of them.
pub fn strict_json(text: &str) -> String {
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::with_capacity(text.len());
    let mut at = 0;
    let mut in_string = false;

    while at < chars.len() {
        let ch = chars[at];
        if in_string {
            out.push(ch);
            if ch == '\\' && at + 1 < chars.len() {
                out.push(chars[at + 1]);
                at += 1;
            } else if ch == '"' {
                in_string = false;
            }
            at += 1;
            continue;
        }

        match (ch, chars.get(at + 1)) {
            ('"', _) => {
                in_string = true;
                out.push(ch);
                at += 1;
            }
            ('/', Some('/')) => {
                while at < chars.len() && chars[at] != '\n' {
                    at += 1;
                }
            }
            ('/', Some('*')) => {
                at += 2;
                while at < chars.len() && !(chars[at] == '*' && chars.get(at + 1) == Some(&'/')) {
                    at += 1;
                }
                at += 2;
            }
            (',', _) => {
                let next = chars[at + 1..]
                    .iter()
                    .enumerate()
                    .find(|(_, ch)| !ch.is_whitespace());
                // A comma followed, past whitespace and comments, by a closer.
                let trailing = match next {
                    Some((_, '}')) | Some((_, ']')) => true,
                    Some((offset, '/')) => {
                        let rest: String = chars[at + 1 + offset..].iter().collect();
                        strict_json(&rest).trim_start().starts_with(['}', ']'])
                    }
                    _ => false,
                };
                if !trailing {
                    out.push(',');
                }
                at += 1;
            }
            _ => {
                out.push(ch);
                at += 1;
            }
        }
    }
    out
}

#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct Rendered {
    pub env_changed: bool,
    pub policy_changed: bool,
}

/// Render both files from `settings` over the image `defaults`.
pub fn all(
    paths: &Paths,
    defaults: &dyn Env,
    settings: &BTreeMap<String, String>,
    log: &Log,
) -> Result<Rendered, String> {
    // What the device reports now: {node.name} when none is set, {node.id},
    // {net.ip} and the other read-only keys.
    let live = live(paths);

    let env_changed = store::replace_if_changed(
        &paths.generated_env(),
        env_file(settings, defaults, &live, log).as_bytes(),
        0o644,
    )
    .map_err(|err| format!("{}: {err}", paths.generated_env().display()))?;

    let effective = state::Effective::new(defaults, settings, log).with_live(live);
    let policy_changed = render_policy(paths, &effective)?;

    Ok(Rendered {
        env_changed,
        policy_changed,
    })
}

/// The name derived from the node id, or `None` without a machine id (a
/// development host pointed at a sandbox).
pub fn derived_name(paths: &Paths) -> Option<String> {
    crate::identity::read_node_id(&paths.machine_id)
        .ok()
        .map(|id| crate::identity::friendly_name(&id))
}

/// Everything the device reports rather than stores, as the read-only keys
/// see it right now. Blocking: sysfs, /proc and one getifaddrs.
pub fn live(paths: &Paths) -> state::Live {
    let mut values = crate::net::values(&crate::net::snapshot(paths));
    if let Ok(id) = crate::identity::read_node_id(&paths.machine_id) {
        values.insert("node.id".to_string(), id);
    }
    state::Live {
        derived_name: derived_name(paths),
        values,
    }
}

fn render_policy(paths: &Paths, effective: &state::Effective) -> Result<bool, String> {
    let base = match std::fs::read_to_string(&paths.policy_base) {
        Ok(base) => base,
        // No base (a development host): leave the policy alone rather than
        // write one that carries nothing but the grants.
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(err) => return Err(format!("{}: {err}", paths.policy_base.display())),
    };

    let origins = device_origins(effective, &paths.selftest_origin);
    let body = policy(&base, &origins)?;
    write(&paths.policy, &body)
}

fn write(path: &Path, body: &str) -> Result<bool, String> {
    store::replace_if_changed(path, body.as_bytes(), 0o644)
        .map_err(|err| format!("{}: {err}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    fn settings(pairs: &[(&str, &str)]) -> BTreeMap<String, String> {
        pairs
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect()
    }

    fn factory() -> HashMap<String, String> {
        [("KIOSK_URL".to_string(), "http://127.0.0.1/".to_string())].into()
    }

    #[test]
    fn the_env_file_holds_only_what_was_set_in_registry_order() {
        let log = Log::buffered(true);
        let text = env_file(
            &settings(&[("display.osk", "never"), ("kiosk.url", "https://a.test/")]),
            &factory(),
            &state::Live::default(),
            &log,
        );

        let lines: Vec<&str> = text.lines().filter(|line| !line.starts_with('#')).collect();
        assert_eq!(lines, ["KIOSK_OSK=never", "KIOSK_URL=https://a.test/"]);

        let untouched = env_file(&BTreeMap::new(), &factory(), &state::Live::default(), &log);
        assert!(
            untouched.lines().all(|line| line.starts_with('#')),
            "{untouched}"
        );
    }

    #[test]
    fn the_env_file_carries_the_url_expanded_never_the_template() {
        let log = Log::buffered(true);
        let text = env_file(
            &settings(&[
                ("kiosk.url", "https://{data.shop}.test/?t={data.table}"),
                ("data.shop", "north"),
                ("data.table", "7 a"),
            ]),
            &factory(),
            &state::Live::default(),
            &log,
        );

        assert!(
            text.contains("KIOSK_URL=https://north.test/?t=7%20a\n"),
            "{text}"
        );
        assert!(!text.contains('{'), "{text}");
    }

    #[test]
    fn the_debug_template_never_reaches_the_env_file() {
        let log = Log::buffered(true);
        let text = env_file(
            &settings(&[
                ("debug.enable", "1"),
                ("debug.template", "IP {net.ip}\\nGW {net.gateway}"),
            ]),
            &factory(),
            &state::Live::default(),
            &log,
        );

        let lines: Vec<&str> = text.lines().filter(|line| !line.starts_with('#')).collect();
        assert_eq!(lines, ["KIOSK_DEBUG_SCREEN=1"]);
    }

    #[test]
    fn a_placeholder_in_the_host_moves_the_device_grants() {
        let log = Log::buffered(true);
        let set = settings(&[
            ("kiosk.url", "https://{data.shop}.test/"),
            ("data.shop", "north"),
        ]);
        let defaults = factory();
        let effective = state::Effective::new(&defaults, &set, &log);

        assert_eq!(
            device_origins(&effective, "http://127.0.0.1"),
            ["https://north.test", "http://127.0.0.1"]
        );
    }

    #[test]
    fn origins_follow_the_kiosk_url_as_set() {
        let defaults: HashMap<String, String> =
            [("KIOSK_URL".to_string(), "http://127.0.0.1/".to_string())].into();
        let log = Log::buffered(true);

        let factory = state::Effective::new(&defaults, &BTreeMap::new(), &log);
        assert_eq!(
            device_origins(&factory, "http://127.0.0.1"),
            ["http://127.0.0.1"]
        );

        let deployed = settings(&[
            ("kiosk.url", "https://shop.test/welcome?x=1"),
            (
                "browser.device_origins",
                "https://tools.test http://127.0.0.1",
            ),
        ]);
        let deployed = state::Effective::new(&defaults, &deployed, &log);
        assert_eq!(
            device_origins(&deployed, "http://127.0.0.1"),
            [
                "https://shop.test",
                "http://127.0.0.1",
                "https://tools.test"
            ]
        );
    }

    #[test]
    fn the_shipped_policy_template_parses_and_is_rewritten() {
        let template = include_str!(
            "../../../meta-tessaro-distro/recipes-browser/tessaro-kiosk/files/tessaro-kiosk-policy.json.in"
        );
        // What do_install substitutes into it.
        let base = template
            .replace("@kiosk-origin@", "http://127.0.0.1")
            .replace("@device-origins@", "\"http://127.0.0.1\"");

        let body = policy(
            &base,
            &["https://a.test".to_string(), "http://127.0.0.1".to_string()],
        )
        .unwrap();
        let parsed: Value = serde_json::from_str(&strict_json(&body)).unwrap();

        assert_eq!(
            parsed["SerialAllowAllPortsForUrls"],
            serde_json::json!(["https://a.test", "http://127.0.0.1"])
        );
        assert_eq!(
            parsed["WebHidAllowAllDevicesForUrls"],
            parsed["SerialAllowAllPortsForUrls"]
        );
        assert_eq!(parsed["TranslateEnabled"], Value::Bool(false));
        assert!(body.starts_with("// Generated by tessaro-agent"));
    }

    #[test]
    fn strict_json_keeps_strings_intact() {
        let text = r#"{
  // a comment
  "a": "http://x/y", /* block */
  "b": ["//not a comment", "a,]"],
  "c": 1, // trailing comma follows
}"#;
        let value: Value = serde_json::from_str(&strict_json(text)).unwrap();
        assert_eq!(value["a"], "http://x/y");
        assert_eq!(value["b"][0], "//not a comment");
        assert_eq!(value["b"][1], "a,]");
        assert_eq!(value["c"], 1);
    }

    #[test]
    fn a_trailing_comma_before_a_comment_and_a_closer_is_dropped() {
        let value: Value = serde_json::from_str(&strict_json("[1, 2, // x\n]")).unwrap();
        assert_eq!(value, serde_json::json!([1, 2]));
    }

    #[test]
    fn rendering_twice_changes_nothing_the_second_time() {
        let dir = tempfile::tempdir().unwrap();
        let log = Log::buffered(true);
        let env: HashMap<String, String> = [
            (
                "KIOSK_RUN_DIR".to_string(),
                dir.path().join("run").display().to_string(),
            ),
            (
                "KIOSK_POLICY".to_string(),
                dir.path().join("policy.json").display().to_string(),
            ),
            (
                "KIOSK_POLICY_BASE".to_string(),
                dir.path().join("base.json").display().to_string(),
            ),
        ]
        .into();
        let paths = Paths::load(&env);
        std::fs::write(&paths.policy_base, "{\"TranslateEnabled\": false,}").unwrap();
        let defaults: HashMap<String, String> =
            [("KIOSK_URL".to_string(), "http://127.0.0.1/".to_string())].into();
        let set = settings(&[("kiosk.url", "https://a.test/")]);

        assert_eq!(
            all(&paths, &defaults, &set, &log).unwrap(),
            Rendered {
                env_changed: true,
                policy_changed: true
            }
        );
        assert_eq!(
            all(&paths, &defaults, &set, &log).unwrap(),
            Rendered::default()
        );

        let same_origin = settings(&[("kiosk.url", "https://a.test/other")]);
        assert_eq!(
            all(&paths, &defaults, &same_origin, &log).unwrap(),
            Rendered {
                env_changed: true,
                policy_changed: false
            }
        );

        // Maintenance mode moves what the browser opens, never the grants:
        // a policy change would restart the browser on a public screen.
        let mut maintenance = same_origin.clone();
        maintenance.insert("maintenance.enable".into(), "1".into());
        maintenance.insert(
            "maintenance.url".into(),
            "http://127.0.0.1/maintenance.html".into(),
        );
        assert_eq!(
            all(&paths, &defaults, &maintenance, &log).unwrap(),
            Rendered {
                env_changed: true,
                policy_changed: false
            }
        );
        let env = std::fs::read_to_string(paths.generated_env()).unwrap();
        assert!(
            env.contains("KIOSK_URL=http://127.0.0.1/maintenance.html\n"),
            "{env}"
        );
    }
}
