//! What the device's settings turn into on disk.
//!
//! These files, each written only when its content actually changes - an
//! unchanged render must never restart anything, because a restart is a
//! blank screen in a public place:
//!
//! * `/run/tessaro-kiosk/generated.env`: the settings as `KIOSK_*=value`
//!   lines, for `tessaro-kiosk.service` (`EnvironmentFile=`, after the image
//!   defaults) and for `tessaro-weston-config`. Only the keys that were set:
//!   everything else already comes from the `/usr/lib` defaults.
//! * `/etc/chromium/policies/managed/10-tessaro.json`: the image's policy with
//!   the device-API grants rewritten for the kiosk origin *as set*, not as
//!   built, the proxy while there is one, and the extra certificate
//!   authorities in `/data/tessaro/ca-certs`, over the browser policies in
//!   `tessaro.db` (`policies.rs`). Generated through serde,
//!   because Chromium drops the whole file on one syntax error with a
//!   single `SYSLOG(WARNING)`.
//! * `tessaro.txt` on a Raspberry Pi's boot partition: the settings the
//!   firmware reads at power-on (`device.gpu_mem`), pulled in by an
//!   `include` line at the end of `config.txt`. The image's `config.txt` has
//!   that line; one flashed before it gets it added here, once.
//!
//! Values need no quoting in the env file: the registry has already refused
//! every character systemd's parser would treat specially.

