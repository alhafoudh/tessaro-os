    #[test]
    fn a_stored_browser_policy_is_rendered_once_and_attributed() {
        let dir = tempfile::tempdir().unwrap();
        let log = Log::buffered(true);
        let env: HashMap<String, String> = [
            ("KIOSK_STATE_DIR", dir.path().join("state")),
            ("KIOSK_RUN_DIR", dir.path().join("run")),
            ("KIOSK_POLICY", dir.path().join("policy.json")),
            ("KIOSK_POLICY_BASE", dir.path().join("base.json")),
            ("KIOSK_PROXY_CONFIG", dir.path().join("tinyproxy.conf")),
        ]
        .into_iter()
        .map(|(name, path)| (name.to_string(), path.display().to_string()))
        .collect();
        let paths = Paths::load(&env);
        std::fs::write(&paths.policy_base, r#"{"TranslateEnabled": false}"#).unwrap();
        let none = BTreeMap::new();
        let db = Db::open(&paths.state_dir, &log);
        assert!(all(&paths, &env, &none, &log).unwrap().policy_changed);

        policies::store(
            &db,
            "lockdown",
            "// x\n{\"SpellcheckEnabled\": false,}",
            None,
            None,
        )
        .unwrap();
        assert!(all(&paths, &env, &none, &log).unwrap().policy_changed);
        assert!(!all(&paths, &env, &none, &log).unwrap().policy_changed);

        let entries = effective(&paths, &db).unwrap();
        let source = |key: &str| {
            entries
                .iter()
                .find(|entry| entry.key == key)
                .map(|entry| entry.source.clone())
        };
        assert_eq!(
            source("SpellcheckEnabled"),
            Some(PolicySource::Policy {
                name: "lockdown".to_string()
            })
        );
        assert_eq!(source("TranslateEnabled"), Some(PolicySource::Image));
        assert_eq!(
            source("SerialAllowAllPortsForUrls"),
            Some(PolicySource::Device)
        );

        // A second one setting the same key goes below it, and wins once
        // it is moved to the top.
        let winner = |db: &Db| {
            let body = std::fs::read_to_string(&paths.policy).unwrap();
            let parsed: Value = serde_json::from_str(&strict_json(&body)).unwrap();
            let source = effective(&paths, db)
                .unwrap()
                .into_iter()
                .find(|entry| entry.key == "SpellcheckEnabled")
                .map(|entry| entry.source);
            (parsed["SpellcheckEnabled"].clone(), source)
        };
        policies::store(&db, "second", "{\"SpellcheckEnabled\": true}", None, None).unwrap();
        assert!(!all(&paths, &env, &none, &log).unwrap().policy_changed);
        assert_eq!(winner(&db).0, Value::Bool(false));
        policies::move_to(&db, "second", 1).unwrap();
        assert!(all(&paths, &env, &none, &log).unwrap().policy_changed);
        assert_eq!(
            winner(&db),
            (
                Value::Bool(true),
                Some(PolicySource::Policy {
                    name: "second".to_string()
                })
            )
        );
        policies::remove(&db, "second").unwrap();
        assert!(all(&paths, &env, &none, &log).unwrap().policy_changed);

        // One written by hand that the check refuses is left out, not fatal.
        db.update(|stored: &mut policies::Policies| {
            stored
                .docs
                .push(("bad".to_string(), "{\"CACertificates\": []}".to_string()));
            Ok(())
        })
        .unwrap();
        assert!(!all(&paths, &env, &none, &log).unwrap().policy_changed);
        assert!(log
            .lines()
            .iter()
            .any(|line| line.contains("browser policy bad left out")));

        policies::remove(&db, "lockdown").unwrap();
        assert!(all(&paths, &env, &none, &log).unwrap().policy_changed);
        assert!(source("SpellcheckEnabled").is_some());
        assert!(effective(&paths, &db)
            .unwrap()
            .iter()
            .all(|entry| entry.key != "SpellcheckEnabled"));
        // printer.enable's entries are the device's, whatever it is set to.
        assert_eq!(source("PrintingEnabled"), Some(PolicySource::Device));
    }

